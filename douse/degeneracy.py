"""Detecting and canonicalizing degenerate N-gons.

An N-gon that has lost vertices is not a failure here -- it is a result, and the point of this
module is to make it a legible one. `douse.constraints` explains why degeneration is routed
through FLAT vertices (interior angle pi) rather than through collapsed edges; what is left is to
say how many vertices a shape actually has, and to keep the flat ones from making the
parametrization worse than it needs to be.

WHAT IS EXACT HERE AND WHAT IS NOT. Moving a flat vertex along its own edge does not change the
domain at all -- `V.n = 0`, so `dlam = 0` for every eigenvalue -- so redistributing flat vertices
and re-choosing which vertex anchors the gauge are both EXACTLY domain-preserving, and
`canonicalize` does them. Turning a short EDGE into a flat vertex is not: deleting an edge of
length eps moves `lam` by O(eps), and no threshold makes that free. So a run that collapses an
edge has to be read, not repaired -- `report` is how, and confirming the value means re-solving
in the reduced family.
"""
import numpy as np

from .polygon import gauge_vector, polygon_area, polygon_vertices

__all__ = ['turning_angles', 'interior_angles', 'effective_vertices', 'report',
           'canonicalize', 'canonicalize_p', 'respread', 'collapse_candidates',
           'flatten_candidates',
           'DegeneracyReport']


def edge_lengths(vertices):
    """`|v_k - v_{k-1}|`, so edge `k` ENDS at vertex `k`.

    Deliberately not `lappy.utils.edge_lengths`, which indexes the other way (`v_k -> v_{k+1}`).
    Both are defensible and mixing them is not: `douse.polygon.perimeter_gradient` and
    `constraints.MinEdgeLength` already use this one, so a constraint index and a degeneracy
    index have to mean the same edge. They did not, briefly, and `collapse_candidates` deleted
    the wrong vertex -- producing a "repaired" polygon carrying a 0.053 edge, which is precisely
    the thing it exists to remove.
    """
    v = np.asarray(vertices, dtype=complex)
    return np.abs(v - np.roll(v, 1))


def _as_vertices(obj, perim=None):
    v = np.asarray(obj)
    if np.iscomplexobj(v) and v.ndim == 1:
        return v.astype(complex)
    return polygon_vertices(np.asarray(obj, dtype=float), 1.0 if perim is None else perim)


def turning_angles(vertices):
    """Exterior turning angle at each vertex, in radians; sums to `2 pi` for a simple CCW polygon.

    Zero at a flat vertex, which is the quantity the degeneracy tests are actually about.
    """
    v = np.asarray(vertices, dtype=complex)
    prev_edge = v - np.roll(v, 1)
    next_edge = np.roll(v, -1) - v
    if np.any(np.abs(prev_edge) == 0) or np.any(np.abs(next_edge) == 0):
        raise ValueError('polygon has a zero-length edge; turning angles are undefined there')
    return np.angle(next_edge/prev_edge)


def interior_angles(vertices):
    """Interior angle at each vertex, in radians. `pi` exactly at a flat vertex."""
    return np.pi - turning_angles(vertices)


def effective_vertices(vertices, angle_tol=1e-6):
    """How many GENUINE corners the shape has: vertices whose turning angle exceeds `angle_tol`.

    This is the observable a degenerating run needs. An N-gon reported with `M < N` here is an
    M-gon wearing `N - M` flat vertices, and its spectrum is the M-gon's.
    """
    return int(np.sum(np.abs(turning_angles(vertices)) > angle_tol))


class DegeneracyReport(dict):
    """What a shape has actually become. Attribute access, like `OptimizeResult`."""

    def __getattr__(self, name):
        try:
            return self[name]
        except KeyError as exc:
            raise AttributeError(name) from exc

    def __repr__(self):
        return (f'DegeneracyReport(n={self.n} -> effective {self.n_effective} '
                f'(soft {self.n_effective_soft}), flat={list(self.flat_idx)}, '
                f'min|turn|={np.degrees(self.min_abs_turning):.3g} deg, '
                f'min_edge={self.min_edge:.3g}, verdict={self.verdict!r})')


def report(vertices, angle_tol=1e-6, soft_tol=5e-2, edge_tol=None, perim=None):
    """Has this shape degenerated, and how?

    `angle_tol` is an EXACTLY-flat test and is deliberately tight; `soft_tol`, 5e-2 rad or about
    2.9 degrees, catches a vertex that is on its way. The distinction matters because an optimizer approaching
    a degeneracy sits at neither: measured on `max lam_3/lam_1` at N=5, a converged run carried a
    vertex 1.4 degrees from flat, which `angle_tol` calls a genuine corner and `soft_tol` calls
    what it is. Reporting only the tight test made that run read as `n_effective = 5` when the
    interesting fact was that it had all but lost a vertex.

    `edge_tol` defaults to `1e-4` of the perimeter. The two verdicts are deliberately kept apart:
    a shape that degenerated by FLATTENING is fully described by its effective vertex count and
    can be canonicalized exactly, while one that degenerated by COLLAPSING AN EDGE cannot -- its
    reported eigenvalues belong to a shape that is an M-gon to within `O(min_edge)`, and the
    number needs re-solving in the M-gon family before it means anything.
    """
    v = _as_vertices(vertices, perim)
    n = len(v)
    lens = edge_lengths(v)
    P = float(lens.sum())
    etol = float(edge_tol) if edge_tol is not None else 1e-4*P

    turn = turning_angles(v)
    flat_idx = np.flatnonzero(np.abs(turn) <= angle_tol)
    near_flat_idx = np.flatnonzero(np.abs(turn) <= float(soft_tol))
    short_idx = np.flatnonzero(lens <= etol)
    n_eff = n - len(flat_idx)

    if len(short_idx):
        verdict = ('an edge has collapsed: this is an M-gon only to within O(min_edge), and the '
                   'eigenvalues need re-solving in the reduced family before they mean anything')
    elif len(flat_idx):
        verdict = ('degenerate by flattening: exactly an M-gon, and `canonicalize` rewrites it '
                   'without changing the domain')
    elif len(near_flat_idx):
        verdict = (f'{len(near_flat_idx)} vertex/vertices within '
                   f'{np.degrees(soft_tol):.2g} degrees of flat: degenerating, not yet degenerate')
    else:
        verdict = 'non-degenerate'

    return DegeneracyReport(n=n, n_effective=n_eff, flat_idx=flat_idx, short_idx=short_idx,
                            near_flat_idx=near_flat_idx,
                            n_effective_soft=n - len(near_flat_idx),
                            min_abs_turning=float(np.abs(turn).min()),
                            min_edge=float(lens.min()), perimeter=P,
                            turning=turn, edge_lengths=lens,
                            degenerate=bool(len(flat_idx) or len(short_idx)),
                            collapsed_edge=bool(len(short_idx)), verdict=verdict)


def canonicalize(vertices, angle_tol=1e-6, perim=None):
    """Rewrite the polygon with its flat vertices spread out and a genuine corner anchoring.

    EXACTLY DOMAIN-PRESERVING, and that is the whole licence for doing it: a flat vertex sits in
    the interior of a straight edge, so where along that edge it sits is not a property of the
    domain. Two things are fixed, both of which cost an optimizer real accuracy:

    **Flat vertices pile up.** Sliding one is free, so nothing stops a run from parking several
    of them on top of each other, which reintroduces the short edges the whole scheme exists to
    avoid. They are redistributed here: the `M` genuine corners are kept, and the `N - M` spare
    vertices are placed to split the longest edges as evenly as possible.

    **The anchor vertex must not be flat.** `polygon.d_vertices_dp` determines `x_0` implicitly
    from the perimeter constraint, dividing by `dP/dx_0 = Re(u_0 - u_1)` -- which is exactly zero
    when `v_0` is flat, and the Jacobian raises. Relabelling which vertex is `v_0` is a rotation
    of the index, so it changes `p` and not the shape; the corner furthest from flat is chosen.

    Returns the canonicalized vertices. Pass `perim` to also get `param_vector` applied.
    """
    v = _as_vertices(vertices, perim)
    n = len(v)
    turn = turning_angles(v)
    keep = np.flatnonzero(np.abs(turn) > angle_tol)
    if len(keep) == n:
        return v
    if len(keep) < 3:
        raise ValueError(f'only {len(keep)} genuine corners remain, which is not a polygon; the '
                         f'shape has degenerated further than this can express')

    return respread(v[keep], n)


def respread(corners, n):
    """Write the polygon with `corners` genuine corners as an `n`-gon, flat vertices spread out.

    The `n - len(corners)` spare vertices split the longest edges as evenly as they can, so no
    short edge is created. Exactly domain-preserving -- every inserted vertex lies in the
    interior of an existing edge -- and the result is anchored on the corner furthest from flat,
    because `polygon.polygon_vertices` cannot represent a polygon whose `v_0` is flat (the two
    closing edges are then collinear and the closing budget equals `|v_1|` exactly).
    """
    corners = np.asarray(corners, dtype=complex)
    m = len(corners)
    if m < 3:
        raise ValueError(f'{m} corners is not a polygon')
    if n < m:
        raise ValueError(f'cannot write an {m}-corner polygon with only {n} vertices')

    e = np.roll(corners, -1) - corners
    lens = np.abs(e)
    splits = np.ones(m, dtype=int)
    for _ in range(n - m):
        splits[int(np.argmax(lens/splits))] += 1   # the edge whose pieces are currently longest

    out = np.array([corners[i] + (t/splits[i])*e[i]
                    for i in range(m) for t in range(splits[i])], dtype=complex)
    assert len(out) == n, (len(out), n)

    out = np.roll(out, -int(np.argmax(np.abs(turning_angles(out)))))
    if polygon_area(out) < 0:
        out = out[::-1]
    return out


def flatten_candidates(vertices, soft_tol=5e-2, perim=None, min_frac=0.15):
    """For each nearly-flat vertex, the polygon with that vertex projected EXACTLY onto flat.

    WHY A MOVE AND NOT A LIMIT. `lam_k/lam_1` has a KINK at the flat configuration, not a smooth
    maximum. Measured on the sqrt(8/3) rectangle written as a pentagon, sweeping the fifth vertex
    through the edge it sits on (`h` its normal offset):

        dF/dh -> +3.413956  as h -> 0 from the reentrant side
        dF/dh -> -1.234267  as h -> 0 from the convex side
        F(0)   = 35/11 exactly, and F(+-1e-08) are both BELOW it

    Continuous, both one-sided derivatives finite and nonzero, opposite in sign: a concave kink
    whose maximum is exactly at the degeneracy. The cause is that the corner exponent
    `nu = pi/omega` crosses 1 there -- reentrant and singular on one side, convex on the other --
    so the two sides are genuinely different problems meeting at a point.

    No first-order model can land on that. A trust-region method approaching it proposes a step
    of size `Delta`, overshoots the kink, is rejected, halves, and repeats: the radius collapses
    geometrically while the iterate creeps. That is exactly what `max lam_3/lam_1` at N=5 does --
    stalling 1.4 degrees short with the radius at 5.7e-15 -- and it is the same pathology as the
    eigenvalue degeneracy `cluster_opt` exists for, except that this one is geometric.

    So the flat configuration is offered as a trial STEP: project, evaluate, accept if better.
    `min_frac` refuses a projection that would put the vertex within that fraction of either
    neighbour, which would trade a flat vertex for a short edge.
    """
    v = np.asarray(vertices, dtype=complex)
    n = len(v)
    P = float(edge_lengths(v).sum()) if perim is None else float(perim)
    turn = turning_angles(v)

    out = []
    for j in np.flatnonzero(np.abs(turn) <= float(soft_tol)):
        a, b = v[(j - 1) % n], v[(j + 1) % n]
        d = b - a
        if d == 0:
            continue
        # orthogonal projection of v_j onto the segment a -> b
        sfrac = float(((v[j] - a)*np.conj(d)).real/abs(d)**2)
        if not (min_frac <= sfrac <= 1.0 - min_frac):
            continue
        cand = v.copy()
        cand[j] = a + sfrac*d
        cand = cand*P/float(edge_lengths(cand).sum())
        if abs(turning_angles(cand)[j]) > 1e-9:
            continue                            # projection did not actually flatten it
        out.append(cand)
    return out


def collapse_candidates(vertices, edge_idx=None, perim=None):
    """The shapes you get by removing the shortest edge, each written back as an `n`-gon.

    NOT DOMAIN-PRESERVING, and it is not meant to be. Deleting an edge of length `eps` moves
    `lam` by `O(eps)`, so no threshold makes this free -- which is exactly why it is offered as a
    trial STEP for the optimizer's accept/reject test rather than as a rewrite. The point is to
    cross between the two representations of a degenerate shape, which a local method cannot do
    on its own: a short edge and a flat vertex describe nearly the same domain but sit in
    completely different regions of `p`-space.

    Removing edge `j`, which runs `v_{j-1} -> v_j`, means keeping one of its endpoints. Both are
    returned (the caller evaluates and picks), each re-expressed with the freed vertex spread
    onto the longest remaining edge, and rescaled to `perim`.
    """
    v = np.asarray(vertices, dtype=complex)
    n = len(v)
    if n < 4:
        raise ValueError(f'collapsing an edge of a {n}-gon leaves fewer than 3 vertices')
    lens = edge_lengths(v)
    P = float(lens.sum()) if perim is None else float(perim)
    j = int(np.argmin(lens)) if edge_idx is None else int(edge_idx)

    out = []
    for drop in ((j - 1) % n, j % n):              # edge j runs v_{j-1} -> v_j; keep one end
        corners = np.delete(v, drop)
        try:
            cand = respread(corners, n)
        except ValueError:
            continue
        cand = cand*P/float(edge_lengths(cand).sum())
        out.append(cand)
    return out


def canonicalize_p(p, perim=1.0, angle_tol=1e-6):
    """`canonicalize` in parameter space: `p -> p`, same domain, healthier coordinates.

    Goes back through `polygon.gauge_vector` rather than `param_vector`, because `param_vector`
    re-rolls the labelling to put the longest side last and would undo the anchor choice --
    measured, on the 8-gon square, by the round trip then raising "no such polygon exists".
    """
    v = canonicalize(polygon_vertices(np.asarray(p, dtype=float), perim), angle_tol=angle_tol)
    return gauge_vector(v, perim, anchor=0)
