"""Slurm array jobs for a run spec: one job per cell, one start per task.  (2026-10-16)

    uv run python -m benchmarks.slurm benchmarks/specs/thesis_ratio_v0.toml --dry-run
    uv run python -m benchmarks.slurm benchmarks/specs/thesis_ratio_v0.toml [--out DIR]

Writes `<out>/<cell>.sbatch` for every cell of the spec and prints the `sbatch` lines to submit
them. IT NEVER SUBMITS: the person running the grid submits on the cluster, by hand.
`--dry-run` prints the scripts and writes nothing.

THE LAYOUT, and why each piece is what it is:

  - ONE START PER TASK (`--array=0-(starts-1)`, `--start-index $SLURM_ARRAY_TASK_ID`). Starts
    are independent and a start is the unit that crashes, so a failed task costs one start and
    is resubmitted by index (`sbatch --array=3 <cell>.sbatch`).
  - ONE LEDGER PER TASK, `<out>/<cell>/task_<i>.jsonl`. Tasks never share a file, so no two
    processes append to one ledger; `summarize_grid --dir <out>` pools a cell's task files.
    A resubmitted task resumes its own file like any ledger (`ratio_multistart`).
  - BLAS THREADS PINNED TO 1, with `--cpus-per-task=1`. Each task is one serial start; a BLAS
    that sizes itself from the node's core count oversubscribes the node many times over.
  - MEMORY AND TIME FROM THE SPEC (`slurm_mem`, `slurm_time`, and optionally `slurm_partition`,
    `slurm_account`; `douse.spec`), which are not part of its content hash. A spec without them
    gets `DEFAULT_MEM`/`DEFAULT_TIME`, and the flags here override either.
  - PATHS RELATIVE TO THE douse CHECKOUT the job runs in (`$DOUSE_ROOT`, else the directory
    `sbatch` was run from), so scripts generated on one machine run on another.
"""
import argparse
import os
import pathlib
import shlex

from douse import spec as spec_mod

# N = 6 runs peaked at 0.9-1.4 GB after the pencil cache fix (`docs/todo.md`); N = 12 is not
# measured yet. A guess with headroom, used only when the spec names none.
DEFAULT_MEM = '4G'
DEFAULT_TIME = '24:00:00'
BLAS_VARS = ('OMP_NUM_THREADS', 'OPENBLAS_NUM_THREADS', 'MKL_NUM_THREADS', 'VECLIB_NUM_THREADS',
             'VECLIB_MAXIMUM_THREADS', 'NUMEXPR_NUM_THREADS')


def cell_name(spec, N, k):
    """`N6_k2` (or `N6_k2_convex`): the cell's ledger stem, and its task directory's name."""
    return spec.ledger_name(N, k)[:-len('.jsonl')]


def _rel(path, root):
    """`path` relative to `root` when it lies under it, else as given."""
    p = pathlib.Path(path).resolve()
    try:
        return str(p.relative_to(pathlib.Path(root).resolve()))
    except ValueError:
        return str(path)


def mail_address(flag=None):
    """Where Slurm mails END/FAIL notices: `--mail`, else `$DOUSE_SLURM_MAIL`, else nobody.

    An environment variable rather than a spec key because the specs are in a public repository
    and an address is personal: set it once in the cluster's `~/.bashrc`."""
    return flag or os.environ.get('DOUSE_SLURM_MAIL') or None


def mail_lines(address):
    """`--mail-type=END,FAIL`: one mail when the whole array ends and one per failed task --
    never `ARRAY_TASKS`, which mails every task of every array."""
    if not address:
        return []
    return ['#SBATCH --mail-type=END,FAIL', f'#SBATCH --mail-user={address}']


def resources(spec, mem=None, time=None, partition=None, account=None, mail=None):
    """`{mem, time, partition, account, mail}`: a flag wins, then the spec (or for mail the
    environment), then the default."""
    return dict(mem=mem or spec.slurm_mem or DEFAULT_MEM,
                time=time or spec.slurm_time or DEFAULT_TIME,
                partition=partition or spec.slurm_partition,
                account=account or spec.slurm_account,
                mail=mail_address(mail))


def script(spec, N, k, spec_path, out, res, runner='uv run python'):
    """The sbatch script for one cell, as text. `spec_path` and `out` are relative to the douse
    checkout (or absolute)."""
    cell = cell_name(spec, N, k)
    task_dir = f'{out}/{cell}'
    lines = ['#!/bin/bash',
             f'#SBATCH --job-name=douse_{spec.name}_{cell}',
             f'#SBATCH --array=0-{spec.starts - 1}',
             '#SBATCH --ntasks=1',
             '#SBATCH --cpus-per-task=1',
             f"#SBATCH --mem={res['mem']}",
             f"#SBATCH --time={res['time']}"]
    if res['partition']:
        lines.append(f"#SBATCH --partition={res['partition']}")
    if res['account']:
        lines.append(f"#SBATCH --account={res['account']}")
    lines += mail_lines(res.get('mail'))
    # Slurm does not create the log directory and a missing one fails the task silently, so it
    # is created when the scripts are written (`main`), not here.
    lines += [f'#SBATCH --output={out}/logs/{cell}_%A_%a.out',
              '',
              f'# spec {spec.name} @ {spec.sha}, cell N={N} k={k} (0-based; lam_{k + 1}/lam_1), '
              f'{spec.starts} start(s), one per task.',
              '# Generated by benchmarks/slurm.py; submit from the douse checkout.',
              'set -euo pipefail',
              'cd "${DOUSE_ROOT:-$SLURM_SUBMIT_DIR}"',
              '']
    lines += [f'export {v}=1' for v in BLAS_VARS]
    i = '${SLURM_ARRAY_TASK_ID}'
    lines += ['',
              f'mkdir -p {shlex.quote(task_dir)}',
              f'{runner} -m benchmarks.ratio_multistart --spec {shlex.quote(spec_path)} '
              f'--N {N} --k {k} --start-index {i} --out "{task_dir}/task_{i}.jsonl"',
              '']
    return '\n'.join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('spec', help='a run spec, benchmarks/specs/*.toml')
    ap.add_argument('--out', default=None,
                    help='where the jobs write, relative to the douse checkout '
                         '(default: benchmarks/run/slurm/<spec name>)')
    ap.add_argument('--mem', default=None, help='override the spec (sbatch --mem)')
    ap.add_argument('--time', default=None, help='override the spec (sbatch --time)')
    ap.add_argument('--partition', default=None)
    ap.add_argument('--account', default=None)
    ap.add_argument('--mail', default=None,
                    help='mail END/FAIL notices here (default: $DOUSE_SLURM_MAIL, else none)')
    ap.add_argument('--runner', default='uv run python',
                    help="how a task runs Python in the douse checkout (default: 'uv run python')")
    ap.add_argument('--dry-run', action='store_true', help='print the scripts; write nothing')
    args = ap.parse_args(argv)

    spec = spec_mod.load(args.spec)
    root = spec_mod.PACKAGE_ROOT
    out = args.out or f'benchmarks/run/slurm/{spec.name}'
    spec_path = _rel(args.spec, root)
    res = resources(spec, args.mem, args.time, args.partition, args.account, args.mail)
    print(f'# spec {spec.name} @ {spec.sha}: {len(spec.cells)} cell(s) x {spec.starts} start(s); '
          f"mem {res['mem']}, time {res['time']} per task"
          + ('' if spec.slurm_mem and spec.slurm_time else
             f' (spec sets {"neither" if not (spec.slurm_mem or spec.slurm_time) else "one"};'
             f' defaults {DEFAULT_MEM}, {DEFAULT_TIME})'))

    paths = []
    for N, k in spec.cells:
        text = script(spec, N, k, spec_path, out, res, args.runner)
        path = f'{out}/{cell_name(spec, N, k)}.sbatch'
        paths.append(path)
        if args.dry_run:
            print(f'\n# ---- {path}\n{text}')
            continue
        dest = root / path if not os.path.isabs(path) else pathlib.Path(path)
        dest.parent.mkdir(parents=True, exist_ok=True)
        (dest.parent / 'logs').mkdir(exist_ok=True)
        dest.write_text(text)
    print(f"\n# {'would write' if args.dry_run else 'wrote'} {len(paths)} script(s). "
          'Submit by hand, from the douse checkout:')
    print(f'mkdir -p {out}/logs')
    for path in paths:
        print(f'sbatch {path}')
    print(f'# then: uv run python -m benchmarks.summarize_grid --dir {out}')


if __name__ == '__main__':
    main()
